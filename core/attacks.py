def get_payload_by_text(text: str):
    """根据用户消息原文反查内置用例（离线模拟模型用它来决定行为）。"""
    core = text.strip()
    for p in PAYLOADS:
        if p["payload"].strip() == core:
            return p
    return None


def case_label(p: dict) -> str:
    """生成界面下拉框显示用的标签，如 'P01 直接越狱｜指令覆盖'。"""
    return f"{p['id']} {p['name']}｜{p['category']}"
